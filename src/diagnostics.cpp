const DiagnosticInfo* find_diagnostic(std::string_view code) {
    const auto& c = diagnostic_catalog();
    auto it = std::find_if(c.begin(), c.end(), [&](const DiagnosticInfo& d) { return d.code == code; });
    return it == c.end() ? nullptr : &*it;
}

